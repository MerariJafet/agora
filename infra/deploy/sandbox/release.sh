#!/usr/bin/env bash
# AGORA pilot release: deploy ONE git commit and prove it is the one serving.
#
#   sudo infra/deploy/sandbox/release.sh [--dry-run] <git-ref>     # e.g. main, v0.2.0, 625ea3a
#
# Replaces the hand-made /opt/agora-releases/<name> + receipt.json routine:
#   1. resolves <git-ref> to a full sha in a bare mirror (/opt/agora-ops/agora.git);
#   2. extracts that exact tree with `git archive` into /opt/agora-releases/<date>-<sha12>
#      (immutable: no working copy, no local edits possible) and writes REVISION;
#   3. dumps the database before any migration;
#   4. recreates the stack from that directory with AGORA_BUILD_SHA/AGORA_RELEASE_ID;
#   5. waits until /healthz inside the container reports the same sha;
#   6. writes <release>.receipt.json automatically (commit, previous release, backup, health).
#
# Rollback = rerun with the previous sha (its directory and receipt stay on disk).
set -euo pipefail

DRY_RUN=0
if [ "${1:-}" = "--dry-run" ]; then DRY_RUN=1; shift; fi
REF="${1:?usage: release.sh [--dry-run] <git-ref>}"

REPO_URL="${REPO_URL:-https://github.com/MerariJafet/agora.git}"
MIRROR="${MIRROR:-/opt/agora-ops/agora.git}"
RELEASES="${RELEASES:-/opt/agora-releases}"
BACKUPS="${BACKUPS:-/opt/agora-backups}"
ENV_FILE="${ENV_FILE:-/opt/agora-sandbox.env}"
API_CONTAINER="${API_CONTAINER:-agora-sandbox-agora-api-1}"
DB_CONTAINER="${DB_CONTAINER:-agora-sandbox-agora-postgres-1}"
PUBLIC_HEALTH="${PUBLIC_HEALTH:-https://agora.datateologica.com/healthz}"

log() { printf '%s %s\n' "$(date -u +%H:%M:%SZ)" "$*"; }
run() { if [ "$DRY_RUN" = 1 ]; then echo "  [dry-run] $*"; else "$@"; fi; }

# 1. resolve the ref
if [ ! -d "$MIRROR" ]; then
  run git clone --bare --quiet "$REPO_URL" "$MIRROR"
fi
if [ -d "$MIRROR" ]; then
  git -C "$MIRROR" fetch --quiet --prune origin '+refs/heads/*:refs/heads/*' '+refs/tags/*:refs/tags/*'
  SHA="$(git -C "$MIRROR" rev-parse --verify "$REF^{commit}")"
else
  SHA="$(git ls-remote "$REPO_URL" "$REF" | awk 'NR==1{print $1}')"
  [ -n "$SHA" ] || { echo "cannot resolve $REF (dry-run without mirror needs a branch or tag)"; exit 1; }
fi
ID="$(date -u +%Y%m%d)-${SHA:0:12}"
DIR="$RELEASES/$ID"
OVERRIDE="$RELEASES/$ID.override.yml"
RECEIPT="$RELEASES/$ID.receipt.json"
PREVIOUS="$(docker inspect "$API_CONTAINER" \
  --format '{{index .Config.Labels "com.docker.compose.project.working_dir"}}' 2>/dev/null \
  | sed -E 's#/infra/deploy/sandbox$##' || true)"
log "ref $REF -> $SHA"
log "release $DIR (previous: ${PREVIOUS:-none})"

# 2. immutable tree
if [ -d "$DIR" ]; then
  log "release directory exists, reusing (git archive output is deterministic)"
else
  run mkdir -p "$DIR"
  if [ "$DRY_RUN" = 1 ]; then
    echo "  [dry-run] git archive $SHA | tar -x -C $DIR"
  else
    git -C "$MIRROR" archive "$SHA" | tar -x -C "$DIR"
    echo "$SHA" > "$DIR/REVISION"
  fi
fi
if [ "$DRY_RUN" = 1 ]; then
  echo "  [dry-run] write $OVERRIDE (per-release web volumes, AGORA_BUILD_SHA=$SHA)"
else
  cat > "$OVERRIDE" <<EOF
# Generated by release.sh for $SHA — do not edit; make a new release instead.
volumes:
  agora_web_node_modules:
    name: agora-release-$ID-node-modules
  agora_web_next:
    name: agora-release-$ID-next
services:
  agora-api:
    environment:
      AGORA_BUILD_SHA: "$SHA"
      AGORA_RELEASE_ID: "$ID"
  agora-web:
    mem_limit: 2g
    environment:
      NODE_OPTIONS: --max-old-space-size=1536
EOF
fi

# 2b. never publish legal pages with placeholders (owner-supplied data missing)
if [ -f "$DIR/scripts/check_legal_placeholders.py" ] && [ "${ALLOW_LEGAL_PLACEHOLDERS:-0}" != 1 ]; then
  if [ "$DRY_RUN" = 1 ] && [ ! -d "$DIR/apps" ]; then
    echo "  [dry-run] python3 scripts/check_legal_placeholders.py (tree not extracted)"
  elif ! python3 "$DIR/scripts/check_legal_placeholders.py" "$DIR"; then
    log "REFUSED: legal pages still contain placeholders (see above)"; exit 4
  fi
fi

# 3. backup before migrations
# One dump per attempt: a retry of the same commit (same $ID) after its
# migrations ran must never overwrite the true pre-migration recovery point.
BACKUP="$BACKUPS/$ID/pre-release-$(date -u +%Y%m%dT%H%M%SZ).dump"
run mkdir -p "$BACKUPS/$ID"
if [ "$DRY_RUN" = 1 ]; then
  echo "  [dry-run] pg_dump $DB_CONTAINER > $BACKUP"
else
  docker exec "$DB_CONTAINER" sh -c 'pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Fc' > "$BACKUP.tmp"
  docker exec -i "$DB_CONTAINER" pg_restore --list < "$BACKUP.tmp" > /dev/null
  chmod 600 "$BACKUP.tmp"
  mv "$BACKUP.tmp" "$BACKUP"
  log "backup $BACKUP ($(du -h "$BACKUP" | cut -f1))"
fi

# 4. recreate the stack from the release directory
COMPOSE=(docker compose -f "$DIR/infra/deploy/sandbox/docker-compose.sandbox.yml" -f "$OVERRIDE"
         --env-file "$ENV_FILE")
run "${COMPOSE[@]}" up -d

[ "$DRY_RUN" = 1 ] && { log "dry-run complete"; exit 0; }

# 5. the served build must be the requested one
served=""
for _ in $(seq 1 90); do
  served="$(docker exec "$API_CONTAINER" python -c \
    "import json,urllib.request;print(json.load(urllib.request.urlopen('http://127.0.0.1:8700/healthz',timeout=3))['build']['sha'] or '')" \
    2>/dev/null || true)"
  [ "$served" = "$SHA" ] && break
  sleep 5
done
[ "$served" = "$SHA" ] || { log "FAIL: API serves '${served:-nothing}', expected $SHA"; exit 1; }
log "API serves $SHA"

# The public URL must serve the same build (proves nginx routes to this stack).
public="unchecked"
for _ in $(seq 1 60); do
  public_sha="$(curl -fsS --max-time 10 "$PUBLIC_HEALTH" 2>/dev/null     | python3 -c "import json,sys;print((json.load(sys.stdin).get('build') or {}).get('sha') or '')"     2>/dev/null || true)"
  if [ "$public_sha" = "$SHA" ]; then public="ok"; break; fi
  sleep 10
done

# 6. receipt
cat > "$RECEIPT" <<EOF
{
  "commit": "$SHA",
  "ref": "$REF",
  "release_id": "$ID",
  "deployed_source": "$DIR",
  "previous_source": "${PREVIOUS:-}",
  "backup": "$BACKUP",
  "api_build_sha_verified": true,
  "public_health": "$public",
  "checked_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
EOF
log "receipt $RECEIPT"
[ "$public" = "ok" ] || { log "WARN: public /healthz did not confirm $SHA yet"; exit 3; }
